-- Effect
------------------------------------------------------------

function Effect(job)
    local chance = tonumber(job.settings["Chance Roll"]) or 50
    local chaos = tonumber(job.settings["Chaos Level"]) or 65
    local repeatChance =
        tonumber(job.settings["Repeat Chance"]) or 25
    local reverseChance =
        tonumber(job.settings["Reverse Chance"]) or 20
    local speedChaos =
        tonumber(job.settings["Speed Chaos"]) or 35

    -- Main activation roll
    if not randomChance(chance) then
        return job
    end

    --------------------------------------------------------
    -- Random ArabFunny / Gen Alpha material
    --------------------------------------------------------

    -- The exact library API can vary between NVG versions.
    -- This section is intentionally kept as a clear integration
    -- point for the library functions exposed by your template.
    --
    -- Example library targets:
    --
    --   ArabFunny
    --   Gen Alpha
    --
    -- Recommended media:
    --   short meme clips
    --   reaction clips
    --   Arabic meme audio
    --   Gen Alpha sound effects
    --   short vertical/video snippets
    --   absurd transitions
    --
    -- Replace the following placeholder call with the
    -- corresponding library-selection function from the
    -- template generated by your NVG installation.

    if functions ~= nil then

        ----------------------------------------------------
        -- Random chaos behavior
        ----------------------------------------------------

        if randomChance(chaos) then

            -- Speed manipulation
            if randomChance(speedChaos) then
                local speed = randomSpeed()

                if functions.setSpeed ~= nil then
                    functions.setSpeed(speed)
                end
            end


            -- Reverse
            if randomChance(reverseChance) then
                if functions.reverse ~= nil then
                    functions.reverse()
                end
            end


            -- Repetition / stutter
            if randomChance(repeatChance) then
                if functions.repeatClip ~= nil then
                    local repeats = math.random(2, 5)
                    functions.repeatClip(repeats)
                end
            end

        end

    end

    return job
end


