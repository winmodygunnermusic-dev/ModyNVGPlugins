------------------------------------------------------------
-- Utility
------------------------------------------------------------

local function randomChance(percent)
    return math.random(1, 100) <= percent
end


local function randomSpeed()
    local speeds = {
        0.50,
        0.67,
        0.80,
        1.00,
        1.25,
        1.50,
        1.75,
        2.00,
        2.50
    }

    return speeds[math.random(1, #speeds)]
end


